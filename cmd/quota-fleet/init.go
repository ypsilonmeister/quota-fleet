package main

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/ypsilonmeister/quota-fleet/internal/config"
)

func runInit(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("init", flag.ContinueOnError)
	fs.SetOutput(stderr)

	var cfgPath string
	fs.StringVar(&cfgPath, "config", resolveDefaultConfigPath(), "path to write fleet.yaml")
	fs.StringVar(&cfgPath, "c", resolveDefaultConfigPath(), "path to write fleet.yaml (shorthand)")

	if err := fs.Parse(args); err != nil {
		return 1
	}

	cfgPath = strings.TrimSpace(cfgPath)
	if cfgPath == "" {
		fmt.Fprintln(stderr, "init failed: config path must not be empty")
		return 1
	}

	instanceID, err := generateRandomHex(8)
	if err != nil {
		fmt.Fprintf(stderr, "init failed: generate instance_id: %v\n", err)
		return 1
	}
	instanceID = "fleet-" + instanceID

	coordinatorToken, err := generateRandomHex(32)
	if err != nil {
		fmt.Fprintf(stderr, "init failed: generate coordinator token: %v\n", err)
		return 1
	}

	watchToken, err := generateRandomHex(32)
	if err != nil {
		fmt.Fprintf(stderr, "init failed: generate watch token: %v\n", err)
		return 1
	}

	content := renderInitTemplate(instanceID, coordinatorToken, watchToken)

	if dir := filepath.Dir(cfgPath); dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			fmt.Fprintf(stderr, "init failed: create directory %q: %v\n", dir, err)
			return 1
		}
	}

	f, err := os.OpenFile(cfgPath, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		if errors.Is(err, os.ErrExist) {
			fmt.Fprintf(stderr, "init failed: %s already exists; refusing to overwrite\n", cfgPath)
			return 1
		}
		fmt.Fprintf(stderr, "init failed: create %q: %v\n", cfgPath, err)
		return 1
	}

	writeErr := writeAndClose(f, []byte(content))
	if writeErr != nil {
		_ = os.Remove(cfgPath)
		fmt.Fprintf(stderr, "init failed: write %q: %v\n", cfgPath, writeErr)
		return 1
	}

	fmt.Fprintf(stdout, "initialized %s (mode 0600)\n", cfgPath)
	fmt.Fprintf(stdout, "  instance_id: %s\n", instanceID)
	fmt.Fprintf(stdout, "  api.tokens:  coordinator and watch generated and written to %s (not printed)\n", cfgPath)
	fmt.Fprintf(stdout, "  next:        quota-fleet serve --config %s\n", cfgPath)
	fmt.Fprintf(stdout, "  quota_gate:  optional — uncomment pools/quota in %s and see docs/23-usage-snapshot.md\n", cfgPath)
	return 0
}

func generateRandomHex(numBytes int) (string, error) {
	buf := make([]byte, numBytes)
	if _, err := rand.Read(buf); err != nil {
		return "", err
	}
	return hex.EncodeToString(buf), nil
}

func writeAndClose(f *os.File, data []byte) error {
	if _, err := f.Write(data); err != nil {
		_ = f.Close()
		return err
	}
	if err := f.Chmod(0o600); err != nil {
		_ = f.Close()
		return err
	}
	return f.Close()
}

func renderInitTemplate(instanceID, coordinatorToken, watchToken string) string {
	return fmt.Sprintf(`# quota-fleet configuration (generated by quota-fleet init)
instance_id: %q
state_dir: "./.quota-fleet"

api:
  listen: %q
  tokens:
    - name: coordinator
      token: %q
      scopes: [%s]
    - name: watch
      token: %q
      scopes: [%s]
  require_auth: true

runtime:
  adapter: %q

limits:
  max_claimed: %d
  attempts_cap: %d

hosts:
  local:
    transport: local
    os: linux
    workdir_root: "."

agents:
  claude:
    preflight: "claude --version"
    launch: "claude -p --model {model}"
    resume: "claude -p --resume {session_id}"
    session_log_glob: "~/.claude/projects/*/*.jsonl"
  codex:
    preflight: "codex --version"
    launch: "codex exec --skip-git-repo-check"
    session_log_glob: "~/.codex/sessions/*/*.jsonl"
  agy:
    preflight: "agy --version"
    launch: "agy --model {model} --print"
    prompt_style: argument

# Optional: Quota Gate (see docs/23-usage-snapshot.md)
# pools:
#   my-pool:
#     applies_to: [{ agent: claude }]
#     # short_window: false   # set false only for pools without a short rolling window
#
# quota:
#   usage_file: "./usage.json"
#   usage_format: "v1"        # legacy (default) | v1
#   stale_after: "45m"        # tune from measured collect + sync latency
#   gate_mode: "dry-run"      # off | dry-run | enforce
`, instanceID, config.DefaultAPIListen, coordinatorToken, strings.Join(config.AllAPIScopes, ", "), watchToken, config.ScopeRead, config.RuntimeAdapterSSH, config.DefaultMaxClaimed, config.DefaultAttemptsCap)
}
